const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {compileArchive}=require('./archive.cjs');
const {writeJson}=require('./runtime.cjs');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
async function runArchiveVerification({app,window,createEditor,runtime}){
 const report={testedAt:new Date().toISOString(),checks:{}};
 const query=s=>window.webContents.executeJavaScript(s);
 async function until(label,fn){const end=Date.now()+30000;while(Date.now()<end){if(await fn())return;await pause(80);}throw new Error('Timeout: '+label);}
 await until('real models',()=>query('Boolean(scheduler&&models.size===2)'));
 await query('scheduler.stop();true');
 await until('stop',()=>query('!scheduler.running'));
 const id='b'.repeat(64),scene={id,title:'归档预览验证',turns:runtime.config.characters.map(c=>({characterId:c.id,text:'雨停了。',timeline:[{atMs:0,action:'still'},{atMs:400,action:'happy'}]}))};
 const archive=compileArchive({...scene,turns:scene.turns.map(t=>({...t,timeline:[{atMs:0,action:'happy'}]}))},runtime.config.characters,{published:false});
 for(const [i,t] of archive.turns.entries())t.timeline=scene.turns[i].timeline.map(e=>({...e,command:structuredClone(archive.cast[i].actions[e.action])}));
 runtime.archives.save(archive);
 const editor=createEditor(false);
 if(editor.webContents.isLoading())await new Promise(r=>editor.webContents.once('did-finish-load',r));
 const studio=s=>editor.webContents.executeJavaScript(s);
 await studio(`refreshScenes('${id}')`);
 const denied=await studio(`window.duo.publish('${id}',1)`);assert.match(denied.error,/预览/);
 // Simulate a changed editor action map: playback must use only archived commands.
 for(const c of runtime.config.characters)c.actions.happy={expression:'not-a-real-expression'};
 await studio('document.getElementById("preview-line").click();true');
 await until('one-line preview starts',()=>query(`previewActive&&activeArchive?.sceneId==='${id}'`));
 await until('one-line preview finishes',()=>query('!previewActive'));
 assert.equal(await studio('previewedRevision'),null,'single-line preview is not full approval');
 await studio('document.getElementById("preview-scene").click();true');
 await until('full preview starts',()=>query('previewActive'));
 await until('full preview finishes',()=>query('!previewActive'));
 await until('completion reaches editor',()=>studio('previewedRevision===1'));
 const actions=await query('actionTrace.slice(-4)');
 assert.equal(actions.length,4);assert.ok(actions.every(a=>!a.error));assert.ok(actions.filter(a=>a.expression).every(a=>a.expressionApplied));
 assert.ok(actions.some(a=>a.name==='still'));
 assert.ok(await query('[...models.values()].every(m=>m.internalModel.breath.getParameters().filter(p=>/Angle/.test(p.parameterId)).every(p=>p.weight===0))'));
 assert.ok(await query('[...models.values()].every(m=>m.internalModel.breath.getParameters().some(p=>p.parameterId==="ParamBreath"&&p.weight>0))'));
 const cast=await query('activeCast.map(c=>({id:c.id,x:positions.get(c.id).x,y:positions.get(c.id).y,height:models.get(c.id).height}))');
 assert.ok(Math.abs(cast[0].x-480*.3)<1);
 await query('positionCharacter(activeCast[0].id,170,430);true');
 await studio('document.getElementById("capture-layout").click();true');
 await until('coordinates persisted',async()=>runtime.archives.read(id).revision===2);
 const positioned=runtime.archives.read(id);assert.ok(Math.abs(positioned.cast[0].layout.x-170/480)<.001);
 const stale=await studio(`window.duo.publish('${id}',2)`);assert.match(stale.error,/预览/);
 await studio('document.getElementById("preview-scene").click();true');
 await until('positioned preview',()=>query('previewActive'));
 await until('positioned preview done',()=>query('!previewActive'));
 await until('revision two completed',()=>studio('previewedRevision===2'));
 await studio('document.getElementById("publish-scene").click();true');
 await until('publication confirmed',async()=>runtime.archives.read(id).published);
 await until('rotation resumes',()=>query('!scheduler.paused'));
 await query('scheduler.stop();true');await until('stop final',()=>query('!scheduler.running'));
 // Exercise A -> B -> A with the real SDK: no per-line resets, then one
 // idle reset per actor, including when the user interrupts playback.
 const continuityId='c'.repeat(64),[a,b]=runtime.config.characters;
 const continuityCast=structuredClone(archive.cast);
 const continuityArchive=structuredClone(archive);
 continuityArchive.sceneId=continuityId;continuityArchive.title='句间连续性验证';
 continuityArchive.cast=continuityCast;
 continuityArchive.turns=[a,b,a].map((c,i)=>({characterId:c.id,text:'雨停了，一起走吧。',action:i===0?'pose_l':'happy',timeline:[{atMs:0,action:i===0?'pose_l':'happy',command:structuredClone(continuityCast.find(r=>r.id===c.id).actions[i===0?'pose_l':'happy'])}]}));
 runtime.archives.save(continuityArchive);
 await query('window.continuityStops=0;for(const m of models.values()){const manager=m.internalModel.motionManager;const original=manager.stopAllMotions.bind(manager);manager.stopAllMotions=()=>{window.continuityStops++;original();};}window.duoTrace.length=0;true');
 await studio(`refreshScenes('${continuityId}');`);
 await studio('document.getElementById("preview-scene").click();true');
 await until('third speaking turn',()=>query('window.duoTrace.filter(e=>e.type==="turn").length===3&&previewActive'));
 assert.equal(await query('window.continuityStops'),0,'dialogue boundaries must not stop motions');
 assert.deepEqual(await query('continuity.read().map(s=>s.phase)'),['speaking','listening']);
 await until('continuity scene finished',()=>query('!previewActive'));
 assert.equal(await query('window.continuityStops'),2,'one idle reset per actor only at scene end');
 await pause(1100);
 assert.ok(await query('continuity.read().every(s=>s.phase==="idle"&&!s.blending)'));
 await studio('document.getElementById("preview-scene").click();true');
 await until('interrupt preview starts',()=>query('previewActive&&continuity.read().some(s=>s.phase==="speaking")'));
 await studio('window.duo.stop();true');
 await until('interrupted preview becomes idle',()=>query('!previewActive&&continuity.read().every(s=>s.phase==="idle")'));
 report.checks={realModels:2,archivedCommandsIgnoreGlobalChanges:true,automaticSwayDisabled:true,breathingPreserved:true,stillStopsMotion:true,singleLinePreview:true,fullPreviewRequired:true,coordinatesSaved:true,stalePreviewRejected:true,publishResumesRotation:true,noResetBetweenTurns:true,speakingAndListening:true,smoothIdleAfterCompletion:true,idleAfterInterruption:true,speechDisabled:!runtime.config.tts.enabled};
 report.actions=actions;report.cast=cast;
 const directory=path.join(__dirname,'..','.preview');
 fs.writeFileSync(path.join(directory,'archive-editor.png'),(await editor.webContents.capturePage()).toPNG());
 fs.writeFileSync(path.join(directory,'archive-stage.png'),(await window.webContents.capturePage()).toPNG());
 writeJson(path.join(directory,'archive-verification.json'),report);
 console.log(JSON.stringify({success:true,...report.checks}));app.exit(0);
}
module.exports={runArchiveVerification};
